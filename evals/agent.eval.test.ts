/**
 * Runs the golden set and writes a scorecard to evals/results/.
 * `npm run eval` — deterministic, offline, no API keys.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { afterAll, describe, expect, it } from "vitest";
import { UNIVERSAL } from "./checks";
import { CASES } from "./dataset";
import { evaluate, type CaseReport } from "./harness";

const reports: CaseReport[] = [];

describe("agent evaluation set", () => {
  for (const testCase of CASES) {
    it(`${testCase.category} · ${testCase.id}`, async () => {
      const report = await evaluate(testCase, UNIVERSAL);
      reports.push(report);
      const failures = report.checks.filter((c) => !c.pass).map((c) => `${c.name}: ${c.detail}`);
      expect(failures).toEqual([]);
    });
  }

  afterAll(() => {
    const dir = fileURLToPath(new URL("./results/", import.meta.url));
    mkdirSync(dir, { recursive: true });
    const totals = reports.reduce((t, r) => ({ passed: t.passed + r.passed, total: t.total + r.total }), { passed: 0, total: 0 });
    const categories = [...new Set(reports.map((r) => r.category))].map((category) => {
      const rs = reports.filter((r) => r.category === category);
      const passed = rs.reduce((s, r) => s + r.passed, 0);
      const total = rs.reduce((s, r) => s + r.total, 0);
      return { category, cases: rs.length, casesPassing: rs.filter((r) => r.passed === r.total).length, passed, total };
    });

    const summary = {
      cases: reports.length,
      casesPassing: reports.filter((r) => r.passed === r.total).length,
      checksPassed: totals.passed,
      checksTotal: totals.total,
      categories,
      reports,
    };
    writeFileSync(`${dir}latest.json`, `${JSON.stringify(summary, null, 2)}\n`);

    const lines = [
      "# Agent evaluation scorecard",
      "",
      "Generated by `npm run eval` (deterministic: offline tools with simulated responses, rules-only parsing).",
      "",
      `**${summary.casesPassing}/${summary.cases} cases fully passing · ${totals.passed}/${totals.total} property checks passed**`,
      "",
      "| Category | Cases passing | Checks passed |",
      "|---|---|---|",
      ...categories.map((c) => `| ${c.category} | ${c.casesPassing}/${c.cases} | ${c.passed}/${c.total} |`),
      "",
      "## Cases",
      "",
      "| Case | Category | Checks | Result |",
      "|---|---|---|---|",
      ...reports.map((r) => `| ${r.title} | ${r.category} | ${r.passed}/${r.total} | ${r.passed === r.total ? "✅" : "❌ " + r.checks.filter((c) => !c.pass).map((c) => c.name).join("; ")} |`),
      "",
      "Every produced plan is also checked against universal invariants (prefixed `[inv]` in `latest.json`): trip length, budget-or-approval, pace ceiling, no repeats, budget arithmetic, traceable verified sources, resolvable citations, status consistency and stage trajectory.",
      "",
    ];
    writeFileSync(`${dir}latest.md`, lines.join("\n"));
  });
});
